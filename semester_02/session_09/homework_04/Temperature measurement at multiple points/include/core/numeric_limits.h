/*
 * Предоставляет compile-time информацию о фундаментальных целочисленных типах.
 * Шаблон не содержит таблиц диапазонов, не предполагает конкретную разрядность
 * фундаментальных типов и не использует платформенные #if.
 *
 * Для каждого типа доступны:
 *
 *  min        — минимальное представимое значение;
 *  max        — максимальное представимое значение;
 *  width      — полная разрядность типа в битах;
 *  is_signed  — признак знакового типа.
 *
 * Все свойства являются compile-time константами и могут использоваться
 * в constexpr-контексте.
 *
 * | Тип                     | Знаковость            | Размер                 |
 * | ----------------------- | --------------------- | ---------------------- |
 * | bool                    | —                     | implementation-defined |
 * | char                    | зависит от реализации | implementation-defined |
 * | signed char             | signed                | implementation-defined |
 * | unsigned char           | unsigned              | implementation-defined |
 * | short int               | signed                | ≥ 16 бит               |
 * | unsigned short int      | unsigned              | ≥ 16 бит               |
 * | int                     | signed                | ≥ 16 бит               |
 * | unsigned int            | unsigned              | ≥ 16 бит               |
 * | long int                | signed                | ≥ 32 бит               |
 * | unsigned long int       | unsigned              | ≥ 32 бит               |
 * | long long int           | signed                | ≥ 64 бит               |
 * | unsigned long long int  | unsigned              | ≥ 64 бит               |
 *
 *
 *                           fundamental types
 *                                 │
 *                   ┌─────────────┼──────────────┐
 *                   │             │              │
 *                  bool          char       integer types
 *                                                │
 *                                      ┌─────────┴─────────┐
 *                                      │                   │
 *                                   signed              unsigned
 *
 * ----------------------------------------------------------------------------
 * АРХИТЕКТУРНЫЙ ПРИНЦИП
 * ----------------------------------------------------------------------------
 *
 * ПЕРВОЕ: шаблон не является первичным источником информации о фундаментальных 
 * типах.
 * Первичным источником являются правила самого языка C++, определяющие 
 * фундаментальные типы и их свойства. В частности, стандарт языка непосредственно
 * определяет:
 *
 *   - какие стандартные целочисленные типы существуют;
 *   - какие из них являются знаковыми, а какие беззнаковыми;
 *   - диапазон представимых значений;
 *   - понятие width (ширины) целочисленного типа.
 *
 * ВТОРОЕ: библиотека не хранит заданные диапазоны для типов:
 *
 *   int8_t  -> -128 ... 127
 *   int16_t -> -32768 ... 32767
 *   int32_t -> ...
 *
 * Свойства фундаментального типа T определяются непосредственно средствами,
 * предоставляемыми языком и библиотекой:
 *
 *   is_integral_v<T>
 *   is_signed_v<T>
 *   is_unsigned_v<T>
 *   sizeof(T)
 *
 * Шаблон не определяет свойства T, а транслирует уже существующие свойства типа
 * в интерфейс, удобный для дальнейшего использования в шаблонном коде. Таким 
 * образом, архитектурная зависимость имеет следующий вид:
 *
 *       правила языка C++
 *              |
 *      фундаментальный тип T
 *              |
 *              ----------------------
 *              |                    |
 *         type traits             sizeof(T)
 *              |
 *       numeric_limits<T>
 *              |
 *          алгоритмы
 *
 * ----------------------------------------------------------------------------
 * ЦЕЛОЧИСЛЕННЫЕ ТИПЫ
 * ----------------------------------------------------------------------------
 *
 * Основной шаблон разрешен только для целочисленных типов.
 * Это намеренное ограничение интерфейса, numeric_limits данного уровня библиотеки 
 * описывает именно целочисленные типы и не пытается одновременно моделировать 
 * floating-point типы.
 *
 * Стандартные signed integer types:
 *
 *   signed char
 *   short int
 *   int
 *   long int
 *   long long int
 *
 * Стандартные unsigned integer types:
 *
 *   unsigned char
 *   unsigned short int
 *   unsigned int
 *   unsigned long int
 *   unsigned long long int
 *
 * bool и char также относятся к integral types, однако их семантика не должна 
 * автоматически отождествляться с обычными signed/unsigned integer types. 
 * Поэтому для них предусмотрены отдельные явные специализации numeric_limits.
 *
 * ----------------------------------------------------------------------------
 * ЗНАКОВОСТЬ
 * ----------------------------------------------------------------------------
 *
 * Свойство signed/unsigned не выводится из numeric_limits.*
 * Это принципиально важно для архитектуры библиотеки: недопустимо строить 
 * is_signed_v<T> через numeric_limits<T>, если numeric_limits<T> в свою очередь
 * использует is_signed_v<T>. Источник информации находится уровнем ниже:
 *
 *   signed char       -> signed
 *   short int         -> signed
 *   int               -> signed
 *   long int          -> signed
 *   long long int     -> signed
 *
 *   unsigned char     -> unsigned
 *   unsigned short    -> unsigned
 *   unsigned int      -> unsigned
 *   unsigned long     -> unsigned
 *   unsigned long long-> unsigned
 *
 * Это свойство фиксируется посредством частичных/явных специализаций для
 * фундаментальных типов. numeric_limits использует результат:
 *
 *   is_signed_v<T>
 *   is_unsigned_v<T>
 *
 * Поэтому зависимости между свойствами типов и numeric_limits являются 
 * однонаправленными: type traits -> numeric_limits.
 *
 * ----------------------------------------------------------------------------
 * RANGE И WIDTH
 * ----------------------------------------------------------------------------
 *
 * Для целочисленного типа стандарт определяет непрерывный диапазон представимых 
 * значений.
 * Для signed integer type диапазон имеет вид:
 *
 *   -2^(N-1) ... 2^(N-1)-1
 *
 * Для unsigned integer type:
 *
 *    0 ... 2^N-1, 
 * где N называется width целочисленного типа. Поэтому диапазоны min() и max() 
 * не задаются константными таблицами. Они вычисляются из свойств конкретного 
 * типа T.
 * Для signed типов:
 *
 *   min() = -2^(width-1)
 *   max() =  2^(width-1)-1
 *
 * Для unsigned типов:
 *
 *   min() = 0
 *   max() = 2^width-1
 * 
 * Реализация использует битовые свойства целочисленного типа:
 *
*   signed:
 *       min() -> 1000...000
 *       max() -> 0111...111
 *
 *   unsigned:
 *       min() -> 0000...000
 *       max() -> 1111...111
 *
 * Поэтому max() может быть получен как побитовое отрицание min(): ~min(), как 
 * для signed, так и для unsigned типов.
 *
 * ----------------------------------------------------------------------------
 * WIDTH И ФИЗИЧЕСКИЙ РАЗМЕР ТИПА
 * ----------------------------------------------------------------------------
 *
 * В текущей реализации:
 *
 *   width = sizeof(T) * CHAR_BIT
 *
 * Это выражение определяет полную ширину хранения объекта T в битах.
 * Следует сохранять в памяти архитектурное различие между:
 *
 *   sizeof(T) * CHAR_BIT
 *
 * и width как термином, описывающим диапазон integer-class type в стандарте.
 * Теоретически объектное представление типа может содержать padding bits — биты, 
 * которые входят в физическое представление объекта, но не участвуют 
 * непосредственно в представлении его значения. Поэтому физическая ширина 
 * хранения и количество бит, определяющих диапазон значений, в общем случае 
 * являются различными понятиями.
 * Для целевых фундаментальных типов и поддерживаемых библиотекой платформ 
 * текущая реализация исходит из того, что:
 *
 *   sizeof(T) * CHAR_BIT
 *
 * соответствует используемой нами width.
 * Если в дальнейшем библиотека должна будет поддерживать реализации с padding
 * bits или иные представления целочисленных типов, это место должно быть 
 * пересмотрено отдельно. Не следует забывать, что width является свойством
 * диапазона значений, а sizeof(T) * CHAR_BIT — свойством физического размера 
 * объекта.
 *
 * ----------------------------------------------------------------------------
 * ПОЧЕМУ НЕТ СПЕЦИАЛИЗАЦИЙ ДЛЯ int8_t, uint16_t И Т. П.
 * ----------------------------------------------------------------------------
 *
 * int8_t, uint16_t, int32_t и другие fixed-width integer types являются 
 * typedef/using-псевдонимами конкретных фундаментальных или расширенных 
 * целочисленных типов, если соответствующий тип существует на платформе.
 * Они не должны иметь собственных специализаций numeric_limits. Например, 
 * если:
 *
 *   int32_t == int
 *
 * то numeric_limits<int32_t> автоматически становится numeric_limits<int>.
 * Таким образом, свойства fixed-width типов наследуются от фундаментального 
 * типа, которому соответствует псевдоним.
 * Это устраняет необходимость:
 *
 *   - дублировать специализации;
 *   - хранить платформенные таблицы;
 *   - использовать #if для определения диапазонов;
 *   - предполагать, какой фундаментальный тип имеет конкретную разрядность.
 *
 * Это особенно важно для кроссплатформенного кода.
 *
 * ----------------------------------------------------------------------------
 * НАЗНАЧЕНИЕ numeric_limits
 * ----------------------------------------------------------------------------
 *
 * numeric_limits предназначен прежде всего как единый интерфейс для шаблонных 
 * алгоритмов.
 * Алгоритм не должен знать, является ли T:
 *
 *   int
 *   long
 *   unsigned int
 *   uint32_t
 *   или другим поддерживаемым целочисленным типом.
 *
 * Вместо этого алгоритм может обращаться к:
 *
 *   numeric_limits<T>::min()
 *   numeric_limits<T>::max()
 *   numeric_limits<T>::width
 *   numeric_limits<T>::is_signed
 *
 * и получать характеристики конкретного T. Таким образом, numeric_limits является
 * уровнем абстракции между фундаментальным типом языка и алгоритмами библиотеки.
 *
 * ----------------------------------------------------------------------------
 * ПРИНЦИП РАСШИРЕНИЯ
 * ----------------------------------------------------------------------------
 *
 * При дальнейшем развитии numeric_limits необходимо сохранять главный принцип:
 *
 *   новое свойство должно по возможности извлекаться из фундаментальных свойств 
 *   T, а не добавляться как независимая платформенная константа.
 *
 * Перед добавлением новой специализации или #if необходимо сначала проверить, 
 * нельзя ли получить требуемую характеристику непосредственно из:
 *
 *   - правил языка C++;
 *   - type traits;
 *   - sizeof(T);
 *   - свойств самого типа T;
 *   - compile-time вычислений.
 *
 * Специализация должна появляться только тогда, когда семантика конкретного типа
 * действительно отличается и не может быть корректно выражена общим шаблоном.
 *
 * ----------------------------------------------------------------------------
 * ИТОГ
 * ----------------------------------------------------------------------------
 *
 * numeric_limits является не таблицей характеристик платформы, а compile-time 
 * интерфейсом доступа к характеристикам фундаментального типа.
 * Главный принцип реализации:
 *
 *       НЕ ХРАНИТЬ ЗНАНИЯ О ТИПАХ В numeric_limits,
 *       А ИЗВЛЕКАТЬ ИХ ИЗ САМОГО T.
 *
 * Это позволяет сохранить реализацию компактной, детерминированной, 
 * кроссплатформенной и независимой от конкретной разрядности фундаментальных типов.
 */

#ifndef NUMERIC_LIMITS_H_FOR_THE_COMPONENT_LIBRARY_PROJECT
#define NUMERIC_LIMITS_H_FOR_THE_COMPONENT_LIBRARY_PROJECT

#include <meta.h>
#include <type_traits.h>

#if defined(_MSC_VER)
#include <climits>
#elif defined(__GNUC__) || defined(__clang__)
#include <limits.h>
#endif

namespace core {
	/**
	 * @brief Шаблон предоставляет характеристики фундаментального 
	 *        целочисленного типа.
	 *
	 * Предоставляет основные свойства типа T, необходимые библиотеке: знак, 
	 * ширину представления, количество разрядов значения и максимальную ширину
	 * его десятичного представления. 
	 * Класс предназначен только для целочисленных типов.
	 *
	 * @tparam T целочисленный тип
	 */
	template<typename T, typename = enable_if_t<is_integral_v<T>>>
	struct numeric_limits {

		/**
		 * @brief Предоставляет максимальное значение знакового типа.
		 *
		 * Максимальное значение определяется как побитовое отрицание 
		 * минимального значения.
		 * @return Максимальное значение типа T.
		 */
		template<typename U = T>
		static constexpr enable_if_t<!is_unsigned_v<U>, U>(max)()
			noexcept { return ~(min)(); }

		/**
		 * @brief Предоставляет минимальное значение знакового типа.
		 *
		 * Минимальное значение формируется установкой знакового разряда при 
		 * нулевых остальных разрядах.
		 * @return Минимальное значение типа T.
		 */
		template<typename U = T>
		static constexpr enable_if_t<!is_unsigned_v<U>, U>(min)()
			noexcept { return static_cast<U>((static_cast<unsigned long long>(1) << (width - 1))); }

		/**
		 * @brief Предоставляет максимальное значение беззнакового типа.
		 *
		 * Максимальное значение получается установкой всех разрядов 
		 * представления в единицу.
		 * @return Максимальное значение типа T.
		 */
		template<typename U = T>
		static constexpr enable_if_t<is_unsigned_v<U>, U>(max)()
			noexcept { return ~(min)(); }

		/**
		 * @brief Предоставляет минимальное значение беззнакового типа.
		 *
		 * Для беззнакового типа минимальным значением является ноль.
		 * @return Минимальное значение типа T.
		 */
		template<typename U = T>
		static constexpr enable_if_t<is_unsigned_v<U>, U>(min)()
			noexcept { return U{}; }

		/**
		 * @brief Предоставляет признак знакового типа.
		 *
		 * @c true для знакового типа и @c false для беззнакового.
		 */
		static constexpr bool is_signed = is_signed_v<T>;

		/**
		 * @brief Предоставляет полную ширину представления типа в битах.
		 *
		 * Включает все биты, занимаемые объектом типа T.
		 */
		static constexpr auto width =
			static_cast<unsigned short int>(sizeof(T) * CHAR_BIT);

		/**
		 * @brief Предоставляет количество разрядов, используемых для 
		 *        представления значения.
		 *
		 * Для знаковых типов знаковый разряд не учитывается.
		 * Для беззнаковых типов все разряды участвуют в представлении значения.
		 */
		static constexpr auto digits =
			static_cast<unsigned short int>(is_signed_v<T> ? width - 1 : width);

		/**
		 * @brief Предоставляет максимальную ширину десятичного 
		 *        представления типа.
		 *
		 * Определяет максимальное количество символов, необходимое для записи 
		 * любого значения типа T в десятичной системе без завершающего нулевого
		 * символа. Для знаковых типов дополнительно учитывается один символ 
		 * для знака числа.
		 */
		static constexpr auto decimal_width = []() {
			auto number = (max)();
			constexpr decltype(number) radix{ 10 };
			unsigned short int count{};

			while(number) {
				++count;
				number /= radix;
			}
			if constexpr(is_signed)
				++count;

			return count;
		}();
	};

	/// @cond HIDE_ENUM_BRIEF
	/**
	 * @brief Специализация шаблона для предоставления характеристик типа bool.
	 */
	template<>
	struct numeric_limits<bool> {};

	/**
	 * @brief Специализация шаблона для предоставления характеристик типа char.
	 */
	template<>
	struct numeric_limits<char> {};
	/// @endcond

} /// !namespace core


#endif /// !defined(NUMERIC_LIMITS_H_FOR_THE_COMPONENT_LIBRARY_PROJECT)

