#ifndef FUNCTIONAL_H_FOR_THE_COMPONENT_LIBRARY_PROJECT
#define FUNCTIONAL_H_FOR_THE_COMPONENT_LIBRARY_PROJECT

namespace core {
	/**
	 * @brief Функциональный объект для строгого упорядочивания по возрастанию.
	 *
	 * Вызов comp(lhs, rhs) возвращает true, если lhs должен находиться строго перед rhs в соответствии
	 * с отношением, задаваемым оператором <.
	 * Предикат сравнения, используемый алгоритмами сортировки, должен задавать строгое слабое
	 * упорядочивание (strict weak ordering).
	 *
	 * Строгое слабое упорядочивание обладает следующими свойствами:
	 *
	 * 1. Иррефлексивность:
	 *      comp(a, a) == false.
	 *
	 * 2. Асимметричность:
	 *      если comp(a, b) == true, то comp(b, a) == false.
	 *
	 * 3. Транзитивность:
	 *      если comp(a, b) == true и comp(b, c) == true,
	 *      то comp(a, c) == true.
	 *
	 * 4. Транзитивность эквивалентности:
	 *      если a эквивалентен b, а b эквивалентен c,
	 *      то a эквивалентен c.
	 *
	 * Эквивалентность двух элементов определяется самим предикатом:
	 *      !comp(a, b) && !comp(b, a)
	 *
	 * Следует обратить внимание, что компаратор отвечает на вопрос:
	 *      «Должен ли a находиться строго перед b?»
	 *
	 * а не на вопрос:
	 *      «Меньше ли a или равен ли a значению b?»
	 *
	 * Поэтому оператор <= не может использоваться как предикат строгого слабого упорядочивания:
	 * он нарушает иррефлексивность, поскольку a <= a истинно, и асимметричность, поскольку для
	 * эквивалентных значений одновременно истинны a <= b и b <= a.
	 *
	 * Таким образом, использование <= вместо < является не вопросом реализации алгоритма, а
	 * нарушением семантического контракта предиката сравнения.
	 *
	 * Первичный шаблон объявлен, но не определён. Специализация для void предоставляет прозрачный
	 * компаратор, тип аргументов которого выводится при каждом вызове.
	 */
	template<typename T = void>	struct less;

	template<>
	struct less<> {
		/**
		 * @brief  Проверяет, должен ли lhs находиться строго перед rhs.
		 * @param  lhs левый операнд сравнения
		 * @param  rhs правый операнд сравнения
		 * @return true, если lhs должен находиться перед rhs;
		 *         false в противном случае
		*/
		template<typename T>
		constexpr bool operator()(const T& lhs, const T& rhs) const noexcept {
			return lhs < rhs;
		}
	};


	/**
	 * @brief Функциональный объект для строгого упорядочивания по убыванию.
	 *
	 * Семантика предиката аналогична less<>, но порядок определяется оператором >.
	 * Предикат сравнения должен задавать строгое слабое упорядочивание (strict weak ordering).
	 *
	 * Компаратор отвечает на вопрос:
	 *      «Должен ли a находиться строго перед b?»
	 *
	 * а не на вопрос:
	 *      «Больше ли a или равно ли a значению b?»
	 *
	 * Поэтому оператор >= не может использоваться как предикат строгого слабого упорядочивания.
	 *
	 * Эквивалентность элементов определяется как:
	 *      !comp(a, b) && !comp(b, a)
	 *
	 * и должна быть транзитивной.
	 *
	 * Первичный шаблон объявлен, но не определён. Специализация для void предоставляет прозрачный
	 * компаратор, тип аргументов которого выводится при каждом вызове.
	*/
	template<typename T = void>	struct greater;

	template<>
	struct greater<> {
		/**
		 * @brief  Проверяет, должен ли lhs находиться строго перед rhs.
		 * @param  lhs левый операнд сравнения
		 * @param  rhs правый операнд сравнения
		 * @return true, если lhs должен находиться перед rhs;
		 *         false в противном случае
		 */
		template<typename T>
		constexpr bool operator()(const T& lhs, const T& rhs) const noexcept {
			return lhs > rhs;
		}
	};


	/**
	 * @brief Функциональный объект для сложения двух значений.
	 *
	 * Первичный шаблон объявлен, но не определён. Специализация для void предоставляет прозрачный
	 * компаратор, тип аргументов которого выводится при каждом вызове.
	 */
	template<typename T = void>	struct plus;

	template<>
	struct plus<> {
		/**
		 * @brief  Складывает два значения.
		 * @param  lhs левый операнд сложения
		 * @param  rhs правый операнд сложения
		 * @return результат сложения lhs и rhs.
		 */
		template<typename T>
		constexpr T operator()(const T& lhs, const T& rhs) const noexcept {
			return lhs + rhs;
		}
	};


	/**
	 * @brief Функциональный объект для вычисления максимального значения из двух.
	 *
	 * Первичный шаблон объявлен, но не определён. Специализация для void предоставляет прозрачный
	 * компаратор, тип аргументов которого выводится при каждом вызове.
	 */
	template<typename T = void>	struct max;

	template<>
	struct max<> {
		/**
		 * @brief  Вычисляет максимальное значение из двух.
		 * @param  lhs левый операнд сравнения
		 * @param  rhs правый операнд сравнения
		 * @return максимальное значение из lhs и rhs
		 */
		template<typename T>
		constexpr T operator()(const T& lhs, const T& rhs) const noexcept {
			return lhs > rhs ? lhs : rhs;
		}
	};


	/**
	 * @brief Функциональный объект для вычисления минимального значения из двух.
	 *
	 * Первичный шаблон объявлен, но не определён. Специализация для void предоставляет прозрачный
	 * компаратор, тип аргументов которого выводится при каждом вызове.
	 */
	template<typename T = void>	struct min;
	
	template<>
	struct min<> {
		/**
		 * @brief  Вычисляет минимальное значение из двух.
		 * @param  lhs левый операнд сравнения
		 * @param  rhs правый операнд сравнения
		 * @return Минимальное значение из lhs и rhs
		 */
		template<typename T>
		constexpr T operator()(const T& lhs, const T& rhs) const noexcept {
			return lhs < rhs ? lhs : rhs;
		}
	};

} /// !namespace core

#endif /// !defined(FUNCTIONAL_H_FOR_THE_COMPONENT_LIBRARY_PROJECT)

